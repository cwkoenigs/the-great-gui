#!/usr/bin/env python3
"""tokens.json → Sources/TerminalDesign/Tokens.swift. The design system's values exist once, in
canon's terminal design export; this writes them as Swift. Zero dependencies.

  DS_CANON=~/Developer/canon (default) · python3 scripts/gen_tokens.py [--check]
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

CANON = Path(os.environ.get("DS_CANON") or Path.home() / "Developer" / "canon").expanduser()
SRC = CANON / "terminal-design" / "design-system" / "tokens.json"
OUT = Path(__file__).resolve().parents[1] / "Sources" / "TerminalDesign" / "Tokens.swift"


def s(v: str) -> str:
    return json.dumps(v, ensure_ascii=False)


def table(d: dict[str, str], indent: str = "        ") -> str:
    return "[\n" + "".join(f"{indent}.{k}: {s(v)},\n" for k, v in d.items()) + indent[:-4] + "]"


def main() -> int:
    check = "--check" in sys.argv
    if not SRC.exists():
        print(f"✗ no tokens at {SRC}\n  clone canon to ~/Developer/canon or set DS_CANON to its checkout")
        return 2
    t = json.loads(SRC.read_text())
    color, typ, grid, glyph, frame, mascot = t["color"], t["type"], t["grid"], t["glyphs"], t["frames"], t["mascot"]
    roles: list[str] = color["roles"]
    sem = color["semantic"]
    legend = ", ".join(f"{s(k)}: {s(v)}" for k, v in mascot["legend"].items())
    swift = f'''// GENERATED by scripts/gen_tokens.py from {SRC.name} ({t["name"]} v{t["version"]}, {t["updated"]}). Do not edit.
// The values exist once, in canon's terminal design export; `make tokens` brings a new export in.
import Foundation

public enum Tokens {{
    public static let name = {s(t["name"])}
    public static let version = {s(t["version"])}
    public static let updated = {s(t["updated"])}

    /// The twelve colour roles (hl is the thirteenth: the focused menu row). Colour names a voice or an outcome.
    public enum Role: String, CaseIterable, Sendable {{
        case {", ".join(roles)}
    }}

    public static let dark: [Role: String] = {table(color["dark"])}

    public static let light: [Role: String] = {table(color["light"])}

    /// For a terminal without truecolor, for reference.
    public static let ansi16: [Role: String] = {table(color["ansi16"])}

    public enum Semantic {{
        public static let voiceYou: Role = .{sem["voiceYou"]}
        public static let voiceAgent: Role = .{sem["voiceAgent"]}
        public static let voiceMachine: Role = .{sem["voiceMachine"]}
        public static let edgeInput: Role = .{sem["edgeInput"]}
        public static let edgeApproval: Role = .{sem["edgeApproval"]}
        public static let bandBg: Role = .{sem["band"]["bg"]}
        public static let bandFg: Role = .{sem["band"]["fg"]}
        public static let keyBg: Role = .{sem["key"]["bg"]}
        public static let keyFg: Role = .{sem["key"]["fg"]}
        public static let cursorBg: Role = .{sem["cursor"]["bg"]}
        public static let cursorFg: Role = .{sem["cursor"]["fg"]}
    }}

    public static let colorRules: [String] = {json.dumps(color["rules"], ensure_ascii=False)}

    public enum Typeface {{
        public static let monoFamily = {s(typ["mono"]["family"])}
        public static let monoFallback: [String] = {json.dumps(typ["mono"]["fallback"], ensure_ascii=False)}
        public static let monoSize: Double = {typ["mono"]["size"]}
        public static let lineHeight: Double = {typ["mono"]["lineHeight"]}
        public static let weights: [Int] = {json.dumps(typ["mono"]["weights"])}
        public static let docHeading = {s(typ["doc"]["heading"])}
        public static let docBody = {s(typ["doc"]["body"])}
    }}

    public enum Grid {{
        public static let cols = {grid["cols"]}
        public static let minCols = {grid["minCols"]}
        public static let indent = {grid["indent"]}
        public static let resultIndent = {grid["resultIndent"]}
        public static let labelWidth = {grid["labelWidth"]}
        public static let bannerLeft = {grid["bannerLeft"]}
        public static let mascotWidth = {grid["mascotWidth"]}
        public static let rhythm = {s(grid["rhythm"])}
    }}

    public enum Glyph {{
        public static let prompt = {s(glyph["prompt"])}
        public static let agent = {s(glyph["agent"])}
        public static let run = {s(glyph["run"])}
        public static let result = {s(glyph["result"])}
        public static let rail = {s(glyph["rail"])}
        public static let close = {s(glyph["close"])}
        public static let ok = {s(glyph["ok"])}
        public static let warn = {s(glyph["warn"])}
        public static let err = {s(glyph["err"])}
        public static let select = {s(glyph["select"])}
        public static let choiceOpen = {s(glyph["choice"][0])}
        public static let choiceClose = {s(glyph["choice"][1])}
        public static let sep = {s(glyph["sep"])}
        public static let fold = {s(glyph["fold"])}
        public static let spinner: [String] = {json.dumps(glyph["spinner"], ensure_ascii=False)}
        public static let spinnerFps = {glyph["spinnerFps"]}
        public static let retired: [String] = {json.dumps(glyph["retired"], ensure_ascii=False)}
    }}

    public enum Frame {{
        public static let topLeft = {s(frame["corners"][0])}
        public static let topRight = {s(frame["corners"][1])}
        public static let bottomLeft = {s(frame["corners"][2])}
        public static let bottomRight = {s(frame["corners"][3])}
        public static let rule = {s(frame["rule"])}
        public static let wall = {s(frame["wall"])}
        public static let joinDown = {s(frame["bannerJoins"][0])}
        public static let joinUp = {s(frame["bannerJoins"][1])}
        public static let joinRight = {s(frame["bannerJoins"][2])}
        public static let joinLeft = {s(frame["bannerJoins"][3])}
        public static let meaning = {s(frame["meaning"])}
    }}

    public enum Motion {{
        public static let liveLines = {t["motion"]["liveLines"]}
        public static let foldKey = {s(t["motion"]["foldKey"])}
    }}

    public enum Mascot {{
        public static let width = {mascot["size"][0]}
        public static let height = {mascot["size"][1]}
        /// D dog (brand) · C cat (strong) · k eye (bg) · . empty. Two pixel rows per text row.
        public static let grid: [String] = [
{"".join(f"            {s(row)},{chr(10)}" for row in mascot["grid"])}        ]
        public static let legend: [Character: String] = [{legend}]
    }}
}}
'''
    if check:
        if OUT.exists() and OUT.read_text() == swift:
            print(f"✓ tokens  Tokens.swift agrees with {SRC}")
            return 0
        print(f"✗ tokens  Tokens.swift is stale\n  python3 scripts/gen_tokens.py")
        return 1
    OUT.write_text(swift)
    print(f"✓ tokens  wrote {OUT.relative_to(OUT.parents[2])} from {t['name']} v{t['version']} ({len(roles)} roles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
